def browse_folder():

    global folder_path
    folder_path = filedialog.askdirectory()
    print(f"Выбрана папка: {folder_path}")
    if folder_path:
        print("Содержимое папки:")
        show_folder_contents(folder_path)
        passes = pars(folder_path)
        data = reading_file(passes)
        print("Данные успешно обработаны:", data)
'''Функция вызывает диалоговое окно для выбора папки, аналогично browse_folder1().
 Однако эта версия включает дополнительную обработку файлов внутри выбранной папки.

Параметры: Нет.
Возвращаемое значение: Нет.
Действие:  
Открывает диалоговое окно для выбора папки и сохраняет её путь в глобальной переменной folder_path.
Если путь был выбран, выводит содержимое папки с помощью вызова функции show_folder_contents(folder_path).
Вызывает функцию pars(folder_path) для поиска всех файлов в указанной папке и возвращает список путей к ним.
Передаёт этот список в функцию reading_file(passes), которая обрабатывает данные из найденных файлов.
Выводит результат обработки данных — словарь data.
'''

def show_folder_contents(path):
    for filename in os.listdir(path):
        file_path = os.path.join(path, filename)
        if os.path.isfile(file_path):
            print(f"Файл: {filename}")
        elif os.path.isdir(file_path):
            print(f"Папка: {filename}")
'''
Функция предназначена для вывода списка всех файлов и подпапок в выбранной директории.
Параметр:  
path: Путь до папки, содержимое которой нужно вывести.
Возвращаемое значение: Нет.
Действие:  
Сканирует указанную директорию с использованием os.listdir() и формирует полный путь к каждому элементу.
Проверяет каждый элемент, является ли он файлом (os.path.isfile) или папкой (os.path.isdir).
Выводит название каждого элемента с указанием его типа (файл или папка).
'''


def pars(folder_path):
    passes = []
    for root, dirs, files in os.walk(folder_path):
        for filename in files:
            root_filename = os.path.join(root, filename)
            if "parcel" not in root_filename:
                passes.append(root_filename)
    return passes
'''
Функция сканирует все файлы в заданной папке и возвращает пути ко всем файлам, кроме тех, в имени которых содержится строка "parcel".
Параметр:  
folder_path: Путь до папки, которую нужно обработать.
Возвращаемое значение: Список путей ко всем подходящим файлам.
Действие:  
Использует os.walk(folder_path) для рекурсивного обхода всех вложенных директорий и получения списков файлов.
Для каждого файла проверяется наличие строки "parcel" в полном пути. Если такая строка отсутствует, путь добавляется в итоговый список passes.
Возвращается список путей к файлам, удовлетворяющих условию.
'''

def reading_file(passes):
    data_dict = {}
    i = 0
    for file_path in passes:
        if ".tsv" in file_path:
            try:
                df = pd.read_csv(file_path, sep='\t', skiprows=[0, 2, 3, 4, 5])

                if 'tpm_unstranded' not in df.columns:
                    raise ValueError(f"Столбец 'tpm_unstranded' отсутствует в файле {file_path}")
                series = pd.to_numeric(df['tpm_unstranded'], errors='coerce')
                if 'gene_id' not in data_dict:
                    data_dict['gene_id'] = df['gene_id']

                data_dict[f'tpm_{i}'] = series
                i += 1
            except Exception as e:
                print(f"Ошибка при обработке файла {file_path}: {e}")
    return data_dict

'''
Функция читает данные из TSV-файлов, которые были найдены функцией pars(), и преобразует их в числовые значения, 
создавая словарь, где ключом является путь к файлу, а значением — серия значений из столбца tpm_unstranded.

Параметр:  
passes: Список путей к файлам, которые нужно прочитать.
Возвращаемое значение: Словарь с путями к файлам и соответствующими сериями данных.
Действие:  
Создаёт пустой словарь data_dict для хранения результатов.
Проходит по каждому файлу в списке passes.
Фильтрует файлы с расширением .tsv и пытается их открыть с помощью pd.read_csv(), 
используя табуляцию в качестве разделителя и пропуская первые несколько строк заголовков.
Проверяет наличие столбца tpm_unstranded в каждом файле. Если столбец отсутствует, выбрасывает ошибку.
Преобразует значения столбца tpm_unstranded в числовой формат с помощью pd.to_numeric(), игнорируя некорректные данные.
Добавляет результаты в словарь data_dict, где ключом служит путь к файлу, а значением — преобразованная серия данных.
В случае ошибки при чтении файла выводится соответствующее сообщение.
Возвращает заполненный словарь с результатами обработки всех подходящих файлов.
'''
